"""
DataSentinel AI - Safe Query Security and Validator Engine
Enforces read-only AST safety, keyword blocking, and automatic row capping.
"""
import re
from typing import Tuple


class SQLSecurityException(Exception):
    """Raised when an unsafe or destructive SQL query is detected."""
    pass


class SQLValidator:
    """
    Validates that queries generated by AI are strictly read-only, non-destructive,
    and row-capped.
    """

    # Destructive SQL keywords that are strictly prohibited
    FORBIDDEN_KEYWORDS = [
        r"\bDROP\b",
        r"\bDELETE\b",
        r"\bUPDATE\b",
        r"\bINSERT\b",
        r"\bALTER\b",
        r"\bTRUNCATE\b",
        r"\bREPLACE\b",
        r"\bCREATE\b",
        r"\bATTACH\b",
        r"\bDETACH\b",
        r"\bPRAGMA\b",
        r"\bEXEC\b",
        r"\bEXECUTE\b",
        r"\bVACUUM\b",
        r"\bGRANT\b",
        r"\bREVOKE\b",
    ]

    @classmethod
    def validate_query(cls, sql: str) -> Tuple[bool, str]:
        """
        Validates SQL safety:
        1. Must not contain destructive keywords.
        2. Must start with SELECT or WITH (CTEs).
        3. Must not attempt SQL injection / multiple chained statements (;).
        """
        cleaned = sql.strip().rstrip(";").strip()
        if not cleaned:
            return False, "Query is empty."

        # Check for multiple chained statements (e.g. SELECT 1; DROP TABLE orders)
        # Semicolons inside strings are rare in analytical queries, but simple split checks multi-statements
        statements = [s.strip() for s in cleaned.split(";") if s.strip()]
        if len(statements) > 1:
            return False, "Multiple queries separated by semicolon are prohibited for security."

        query_upper = cleaned.upper()

        # Check for forbidden destructive keywords
        for pattern in cls.FORBIDDEN_KEYWORDS:
            if re.search(pattern, query_upper):
                match = re.search(pattern, query_upper).group(0)
                return False, f"Security Violation: Destructive or forbidden keyword '{match}' detected."

        # Must start with SELECT or WITH
        if not (query_upper.startswith("SELECT") or query_upper.startswith("WITH")):
            return False, "Security Violation: Only SELECT or WITH (CTE) read-only queries are permitted."

        return True, "Query is safe."

    @classmethod
    def enforce_row_limit(cls, sql: str, max_limit: int = 100) -> str:
        """
        Ensures the query has a LIMIT clause that does not exceed max_limit.
        """
        cleaned = sql.strip().rstrip(";").strip()
        limit_match = re.search(r"\bLIMIT\s+(\d+)\b", cleaned, re.IGNORECASE)

        if limit_match:
            existing_limit = int(limit_match.group(1))
            if existing_limit > max_limit:
                # Replace with capped limit
                return re.sub(r"\bLIMIT\s+\d+\b", f"LIMIT {max_limit}", cleaned, flags=re.IGNORECASE)
            return cleaned
        else:
            return f"{cleaned} LIMIT {max_limit}"
